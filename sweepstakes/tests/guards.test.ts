import { describe, expect, it } from "vitest";
import {
  captchaGuard,
  detectCaptcha,
  duplicateGuard,
  findAutomationBan,
  randomIntervalMs,
  rateLimitGuard,
  requiredFieldsGuard,
  termsGuard,
} from "../src/core/guards.js";

describe("detectCaptcha", () => {
  it.each([
    ['<div class="g-recaptcha" data-sitekey="x"></div>', "recaptcha"],
    ['<script src="https://www.google.com/recaptcha/api.js" async></script>', "recaptcha"],
    ['<iframe src="https://www.google.com/recaptcha/api2/anchor?k=x"></iframe>', "recaptcha"],
    ['<textarea name="g-recaptcha-response"></textarea>', "recaptcha"],
    ['<div class="h-captcha" data-sitekey="x"></div>', "hcaptcha"],
    ['<script src="https://js.hcaptcha.com/1/api.js"></script>', "hcaptcha"],
    ['<div class="cf-turnstile" data-sitekey="x"></div>', "turnstile"],
    ['<script src="https://challenges.cloudflare.com/turnstile/v0/api.js"></script>', "turnstile"],
    ["<title>Just a moment...</title>", "cloudflare_challenge"],
  ])("%s → %s", (html, kind) => {
    const r = detectCaptcha({ html });
    expect(r.detected).toBe(true);
    expect(r.kinds).toContain(kind);
  });

  it("フレーム URL からも検出する", () => {
    expect(detectCaptcha({ html: "<p>ok</p>", frameUrls: ["https://newassets.hcaptcha.com/captcha/v1/x"] }).detected).toBe(true);
  });

  it("CAPTCHA のない普通のページは検出しない", () => {
    expect(detectCaptcha({ html: "<form><input name=email><button>送信</button></form>" }).detected).toBe(false);
  });

  it("検出時は needs_manual", () => {
    const g = captchaGuard({ html: '<div class="g-recaptcha"></div>' });
    expect(g).toMatchObject({ ok: false, status: "needs_manual" });
  });
});

describe("findAutomationBan / termsGuard", () => {
  it.each([
    "自動応募ツールやプログラム等を利用した応募は禁止とします。",
    "※ボット、スクリプト等による機械的な応募は無効となります。",
    "応募にあたり、自動化ツールの使用は認めません。",
    "Entries generated by script, macro or any automated means are void.",
    "Use of automated software or bots to enter is prohibited.",
  ])("禁止を検出: %s", (t) => {
    expect(findAutomationBan(t)).not.toBeNull();
    expect(termsGuard([t])).toMatchObject({ ok: false, status: "skipped" });
  });

  it.each([
    "お一人様1回限りの応募とします。締切後の応募は無効です。",
    "当選者には自動返信メールでお知らせします。",
    "応募には会員登録が必要です。",
    "Enter by December 31. One entry per person.",
  ])("誤検知しない: %s", (t) => {
    expect(findAutomationBan(t)).toBeNull();
  });
});

describe("duplicateGuard", () => {
  it("送信済み・手動完了があれば skipped", () => {
    expect(duplicateGuard([{ status: "submitted" }]).ok).toBe(false);
    expect(duplicateGuard([{ status: "done_manual" }]).ok).toBe(false);
  });
  it("失敗・要手動だけなら再試行できる", () => {
    expect(duplicateGuard([{ status: "failed" }, { status: "needs_manual" }]).ok).toBe(true);
    expect(duplicateGuard([]).ok).toBe(true);
  });
});

describe("rateLimitGuard", () => {
  const now = new Date("2026-11-21T12:00:00Z");
  const base = { now, dailyLimit: 30, minIntervalSec: 60, maxIntervalSec: 180 };

  it("日次上限に達したら不可", () => {
    expect(rateLimitGuard({ ...base, submittedToday: 30, lastSubmittedAt: null }).allowed).toBe(false);
    expect(rateLimitGuard({ ...base, submittedToday: 29, lastSubmittedAt: null })).toEqual({ allowed: true, waitMs: 0 });
  });

  it("前回送信からランダム間隔 (60〜180 秒) を空ける", () => {
    const last = new Date(now.getTime() - 30_000);
    expect(rateLimitGuard({ ...base, submittedToday: 1, lastSubmittedAt: last, random: () => 0 }).waitMs).toBe(30_000);
    expect(rateLimitGuard({ ...base, submittedToday: 1, lastSubmittedAt: last, random: () => 1 }).waitMs).toBe(150_000);
    const old = new Date(now.getTime() - 600_000);
    expect(rateLimitGuard({ ...base, submittedToday: 1, lastSubmittedAt: old }).waitMs).toBe(0);
  });

  it("randomIntervalMs は範囲内", () => {
    for (let i = 0; i < 100; i++) {
      const v = randomIntervalMs(60, 180);
      expect(v).toBeGreaterThanOrEqual(60_000);
      expect(v).toBeLessThanOrEqual(180_000);
    }
  });
});

describe("requiredFieldsGuard", () => {
  it("未解決の必須欄があれば needs_manual", () => {
    const g = requiredFieldsGuard([
      { label: "氏名", required: true, resolved: true },
      { label: "応募理由", required: true, resolved: false },
      { label: "任意欄", required: false, resolved: false },
    ]);
    expect(g).toMatchObject({ ok: false, status: "needs_manual" });
    expect(g.reason).toContain("応募理由");
    expect(g.reason).not.toContain("任意欄");
  });
});
