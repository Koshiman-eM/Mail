// フォーム自動入力・送信の結合テスト (ローカル HTTP サーバーのみ使用)
import { existsSync } from "node:fs";
import { afterAll, afterEach, beforeAll, describe, expect, it } from "vitest";
import { enter, runAll, type SweepContext } from "../src/core/service.js";
import { addCampaign, makeTestContext } from "./helpers/context.js";
import { startTestServer, type TestServer } from "./helpers/server.js";

let srv: TestServer;
let ctx: SweepContext;

beforeAll(async () => {
  srv = await startTestServer();
});
afterAll(async () => {
  await srv.close();
});
afterEach(() => {
  srv.received.length = 0;
  ctx?.store.close();
});

const formUrl = (name: string) => `${srv.baseUrl}/forms/${name}`;

describe("通常フォーム", () => {
  it("--submit で正しい値が入力されサーバーに届く", async () => {
    ctx = makeTestContext();
    const c = addCampaign(ctx, { url: formUrl("basic.html"), title: "通常フォーム" });
    const r = await enter(ctx, c.id, { submit: true });

    expect(r.status, r.reason).toBe("submitted");
    expect(r.recorded).toBe(true);
    expect(srv.received).toHaveLength(1);
    const { path, body } = srv.received[0]!;
    expect(path).toBe("/submit");
    expect(body).toMatchObject({
      sei: "山田",
      mei: "太郎",
      sei_kana: "ヤマダ",
      mei_kana: "タロウ",
      zip: "1000001", // maxlength=7 / プレースホルダに合わせてハイフンなし
      pref: "13",
      city: "千代田区",
      addr1: "千代田1-1",
      addr2: "サンプルマンション101",
      tel: "090-1234-5678",
      email: "taro.yamada@example.com",
      email_confirm: "taro.yamada@example.com",
      birth_y: "1990",
      birth_m: "4",
      birth_d: "1",
      gender: "m",
      agree: "yes",
      website: "", // ハニーポット (非表示欄) には触れない
      campaign_code: "AUTUMN",
    });
    expect(body.mailmag).toBeUndefined(); // メルマガは勝手にチェックしない
    expect(ctx.store.listEntries({ campaignId: c.id })[0]?.status).toBe("submitted");
    expect(ctx.store.getCampaign(c.id)?.status).toBe("entered");
  });
});

describe("確認画面付き 2 段階フォーム", () => {
  it("確認画面の「送信する」まで押して完了する", async () => {
    ctx = makeTestContext();
    const c = addCampaign(ctx, { url: formUrl("confirm.html"), title: "2段階" });
    const r = await enter(ctx, c.id, { submit: true });

    expect(r.status, r.reason).toBe("submitted");
    expect(srv.received.map((x) => x.path)).toEqual(["/confirm", "/complete"]);
    const body = srv.received[1]!.body;
    expect(body).toMatchObject({
      fullname: "山田 太郎",
      fullname_kana: "やまだ たろう", // 「ふりがな」表記なのでひらがな
      zip1: "100",
      zip2: "0001",
      address: "東京都千代田区千代田1-1 サンプルマンション101",
      phone: "090-1234-5678",
      mail: "taro.yamada@example.com",
      bd: "1990-04-01",
      sex: "male",
      privacy: "on",
    });
  });
});

describe("送信前ガード", () => {
  it("reCAPTCHA 風の要素があれば needs_manual で送信しない", async () => {
    ctx = makeTestContext();
    const c = addCampaign(ctx, { url: formUrl("captcha.html") });
    const r = await enter(ctx, c.id, { submit: true });
    expect(r.status).toBe("needs_manual");
    expect(r.reason).toMatch(/CAPTCHA/);
    expect(r.filled).toHaveLength(0);
    expect(srv.received).toHaveLength(0);
    expect(ctx.store.listEntries({ campaignId: c.id })[0]?.status).toBe("needs_manual");
  });

  it("規約に自動応募禁止があれば skipped で送信しない", async () => {
    ctx = makeTestContext();
    const c = addCampaign(ctx, { url: formUrl("banned.html") });
    const r = await enter(ctx, c.id, { submit: true });
    expect(r.status).toBe("skipped");
    expect(r.reason).toMatch(/自動応募が禁止/);
    expect(srv.received).toHaveLength(0);
  });

  it("Collector が取得した規約テキストに禁止記述があっても skipped", async () => {
    ctx = makeTestContext();
    const c = addCampaign(ctx, {
      url: formUrl("basic.html"),
      conditions: { terms: "Entries generated by script, macro or any automated means are void." },
    });
    const r = await enter(ctx, c.id, { submit: true });
    expect(r.status).toBe("skipped");
    expect(srv.received).toHaveLength(0);
  });

  it("不明な必須欄があれば needs_manual で送信しない", async () => {
    ctx = makeTestContext();
    const c = addCampaign(ctx, { url: formUrl("unknown_required.html") });
    const r = await enter(ctx, c.id, { submit: true });
    expect(r.status).toBe("needs_manual");
    expect(r.reason).toMatch(/応募の理由/);
    expect(r.reason).toMatch(/ご希望のプレゼント/);
    expect(srv.received).toHaveLength(0);
  });
});

describe("dry-run", () => {
  it("入力はするが送信せず、スクリーンショットを保存し記録もしない", async () => {
    ctx = makeTestContext();
    const c = addCampaign(ctx, { url: formUrl("basic.html") });
    const r = await enter(ctx, c.id); // submit 指定なし = dry-run
    expect(r.status).toBe("dry_run");
    expect(r.recorded).toBe(false);
    expect(r.filled.length).toBeGreaterThan(10);
    expect(r.screenshotPath && existsSync(r.screenshotPath)).toBe(true);
    expect(srv.received).toHaveLength(0);
    expect(ctx.store.listEntries()).toHaveLength(0);
  });

  it("run (dry-run) でも送信されない", async () => {
    ctx = makeTestContext();
    addCampaign(ctx, { url: formUrl("basic.html") });
    addCampaign(ctx, { url: formUrl("confirm.html") });
    const rs = await runAll(ctx);
    expect(rs.map((r) => r.status)).toEqual(["dry_run", "dry_run"]);
    expect(srv.received).toHaveLength(0);
  });
});

describe("重複応募・日次上限", () => {
  it("同じキャンペーンへの 2 回目は skipped で送信しない", async () => {
    ctx = makeTestContext();
    const c = addCampaign(ctx, { url: formUrl("basic.html") });
    expect((await enter(ctx, c.id, { submit: true })).status).toBe("submitted");
    const second = await enter(ctx, c.id, { submit: true });
    expect(second.status).toBe("skipped");
    expect(second.reason).toMatch(/応募済み/);
    expect(srv.received).toHaveLength(1);
  });

  it("URL が同じキャンペーンは重複登録されない", () => {
    ctx = makeTestContext();
    const a = addCampaign(ctx, { url: formUrl("basic.html") });
    const b = addCampaign(ctx, { url: formUrl("basic.html") + "#top" });
    expect(b.id).toBe(a.id);
    expect(ctx.store.listCampaigns()).toHaveLength(1);
  });

  it("日次上限に達したら run は送信を止める", async () => {
    ctx = makeTestContext({ dailyLimit: 1 });
    addCampaign(ctx, { url: formUrl("basic.html"), prizeValueJpy: 99999 });
    addCampaign(ctx, { url: formUrl("confirm.html"), prizeValueJpy: 1 });
    const rs = await runAll(ctx, { submit: true });
    expect(rs.map((r) => r.status)).toEqual(["submitted", "deferred"]);
    expect(srv.received.map((x) => x.path)).toEqual(["/submit"]);
  });

  it("送信間隔の待機が行われる", async () => {
    const waits: number[] = [];
    ctx = makeTestContext({ minIntervalSec: 60, maxIntervalSec: 180 }, { sleep: async (ms) => void waits.push(ms), random: () => 0.5 });
    addCampaign(ctx, { url: formUrl("basic.html"), prizeValueJpy: 99999 });
    addCampaign(ctx, { url: formUrl("confirm.html"), prizeValueJpy: 1 });
    const rs = await runAll(ctx, { submit: true });
    expect(rs.map((r) => r.status)).toEqual(["submitted", "submitted"]);
    expect(waits).toHaveLength(1);
    // 120 秒 (60 + 120 × 0.5) から経過時間を引いた値
    expect(waits[0]!).toBeGreaterThan(110_000);
    expect(waits[0]!).toBeLessThanOrEqual(120_000);
  });
});
